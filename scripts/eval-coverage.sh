#!/usr/bin/env bash
# Builds docs/EVAL-COVERAGE.md: which skills and which of their sections have evals, with the
# latest recorded scores (docs/eval-scores.json, written by scripts/record-eval-scores.sh).
#
# A knowledge case names the sections it tests in a comment line in its prompt.md frontmatter
# (a comment, because `claude plugin eval` rejects frontmatter keys it doesn't know):
#   # covers: ["Section heading"]
# using a `## ` heading from the skill's SKILL.md or references/*.md. Workflow cases (tagged
# `workflow`) and should-not-trigger cases don't need one.
#
# Usage: scripts/eval-coverage.sh          rewrite docs/EVAL-COVERAGE.md
#        scripts/eval-coverage.sh --check  exit 1 if it's out of date or a covers value is wrong

set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$repo_root"

skills_dir="plugins/umbraco-devkit/skills"
evals_dir="plugins/umbraco-devkit/evals"
scores="docs/eval-scores.json"
out="docs/EVAL-COVERAGE.md"

# Headings that hold no rule of their own, so they don't count toward coverage.
not_a_rule='^(Contents|Scope|Sources?|Test it|Reviewing .*|Hand off|Argument)$'

# One line per recorded case: name, with, without, skill loaded, date. Read once, looked up below.
scores_tsv=""
if [[ -f "$scores" ]]; then
  scores_tsv="$(jq -r 'to_entries[] | [.key, (.value.with // "–"), (.value.without // "–"),
    (if .value.runs == null then "–" else "\(.value.skillLoaded)/\(.value.runs)" end),
    (.value.date // "–")] | @tsv' "$scores")"
fi

# One line per case and covered section: case name, section. Read once, looked up below.
covers_tsv="$(for p in "$evals_dir"/*/prompt.md; do
  n="$(basename "$(dirname "$p")")"
  sed -n 's/^# covers:[[:space:]]*//p' "$p" | jq -r --arg n "$n" '.[] | [$n, .] | @tsv' 2>/dev/null || true
done)"

# One line per case and tag: case name, tag.
tags_tsv="$(for p in "$evals_dir"/*/prompt.md; do
  n="$(basename "$(dirname "$p")")"
  sed -n 's/^tags:[[:space:]]*\[\(.*\)\].*/\1/p' "$p" | tr ',' '\n' | tr -d ' ' | sed "s/^/$n\t/"
done)"
tags_of() { awk -F'\t' -v c="$1" '$1 == c { print $2 }' <<<"$tags_tsv"; }
covers_of() { awk -F'\t' -v c="$1" '$1 == c { print $2 }' <<<"$covers_tsv"; }
headings_of() {
  cat "$skills_dir/$1/SKILL.md" "$skills_dir/$1"/references/*.md 2>/dev/null |
    sed -n 's/^## //p' | grep -Ev "$not_a_rule" || true
}
# field <case> <column>: 2 with, 3 without, 4 skill loaded, 5 date; "–" when not recorded.
field() {
  local v
  v="$(awk -F'\t' -v c="$1" -v n="$2" '$1 == c { print $n; exit }' <<<"$scores_tsv")"
  echo "${v:-–}"
}

errors=0
tmp="$(mktemp)"
body="$(mktemp)"
trap 'rm -f "$tmp" "$body"' EXIT

{
  echo "# Eval coverage"
  echo
  echo "Generated by \`scripts/eval-coverage.sh\` from the eval cases in"
  echo "\`$evals_dir/\` and the scores in \`docs/eval-scores.json\`. Don't edit it by hand."
  echo
  echo "- **Sections covered:** the skill's \`## \` sections that at least one eval names in its"
  echo "  \`# covers:\` line. A section with no eval is a rule nobody has proven is needed."
  echo "- **With / Without:** the latest recorded score (0–100) with the plugin and without it."
  echo "  \"–\" means no run has been recorded."
  echo "- **Skill loaded:** in how many recorded with-plugin runs the skill actually loaded."
  echo "- Workflow skills have no plain-Claude equivalent, so they show their cases only."
  echo
  echo "## Summary"
  echo
  echo "| Skill | Kind | Evals | Real bugs | Sections covered |"
  echo "|---|---|---|---|---|"
} > "$tmp"

for skill_file in "$skills_dir"/*/SKILL.md; do
  skill="$(basename "$(dirname "$skill_file")")"

  cases=()
  quiet=()
  real=0
  workflow=false
  for name in $(awk -F'\t' -v s="$skill" '$2 == s { print $1 }' <<<"$tags_tsv" | sort -u); do
    tags="$(tags_of "$name")"
    if grep -qxF should-not-trigger <<<"$tags"; then quiet+=("$name"); continue; fi
    cases+=("$name")
    grep -qxF workflow <<<"$tags" && workflow=true
    grep -qxF real-bug <<<"$tags" && real=$((real + 1))
  done

  {
    echo
    echo "## \`$skill\`"
    echo
  } >> "$body"

  if $workflow; then
    kind="workflow"
    covered="–"
    echo "| Eval | With | Recorded |" >> "$body"
    echo "|---|---|---|" >> "$body"
    for c in "${cases[@]}"; do
      echo "| \`$c\` | $(field "$c" 2) | $(field "$c" 5) |" >> "$body"
    done
  else
    kind="knowledge"
    headings="$(headings_of "$skill")"
    total=0
    hit=0
    echo "| Section | Eval | With | Without | Skill loaded | Recorded |" >> "$body"
    echo "|---|---|---|---|---|---|" >> "$body"
    while IFS= read -r h; do
      [[ -n "$h" ]] || continue
      total=$((total + 1))
      found=false
      for c in "${cases[@]}"; do
        if covers_of "$c" | grep -qxF "$h"; then
          found=true
          echo "| $h | \`$c\` | $(field "$c" 2) | $(field "$c" 3) | $(field "$c" 4) | $(field "$c" 5) |" >> "$body"
        fi
      done
      if $found; then hit=$((hit + 1)); else echo "| $h | **no eval** | | | | |" >> "$body"; fi
    done <<<"$headings"
    covered="$hit/$total"

    # Cases with no covers line, or a covers value that isn't one of the skill's sections.
    unmapped=()
    for c in "${cases[@]}"; do
      cv="$(covers_of "$c")"
      if [[ -z "$cv" ]]; then unmapped+=("$c"); continue; fi
      while IFS= read -r v; do
        if ! grep -qxF "$v" <<<"$headings"; then
          echo "# covers: \"$v\" in $evals_dir/$c/prompt.md is not a section of $skill" >&2
          errors=1
        fi
      done <<<"$cv"
    done
    if [[ ${#unmapped[@]} -gt 0 ]]; then
      {
        echo
        echo "No section: $(printf '`%s` ' "${unmapped[@]}")"
        echo
        echo "These test something with no rule in the skill: a guard for a rule plain Claude was"
        echo "shown to follow (kept so a regression shows up), or a case not yet mapped."
      } >> "$body"
    fi
  fi

  if [[ ${#quiet[@]} -gt 0 ]]; then
    {
      echo
      echo "Stays quiet on: $(printf '`%s` ' "${quiet[@]}")"
    } >> "$body"
  fi

  echo "| [\`$skill\`](#$skill) | $kind | ${#cases[@]} | $real | $covered |" >> "$tmp"
done

cat "$body" >> "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  if ! diff -q "$tmp" "$out" > /dev/null 2>&1; then
    echo "$out is out of date. Run scripts/eval-coverage.sh and commit the result." >&2
    diff -u "$out" "$tmp" | head -40 >&2 || true
    errors=1
  fi
  [[ "$errors" -eq 0 ]] && echo "Eval coverage report is up to date."
  exit "$errors"
fi

cp "$tmp" "$out"
echo "Wrote $out"
exit "$errors"
