using Acme.Reviews.Persistence;
using Microsoft.EntityFrameworkCore;

namespace Acme.Reviews.Services;

internal sealed class ReviewService(IDbContextFactory<ReviewsDbContext> dbFactory, TimeProvider clock)
{
    public async Task<IReadOnlyList<Review>> GetForContentAsync(Guid contentKey)
    {
        await using ReviewsDbContext db = await dbFactory.CreateDbContextAsync();
        return await db.Reviews.AsNoTracking().Where(r => r.ContentKey == contentKey).ToListAsync();
    }

    public async Task MarkVerifiedAsync(int id)
    {
        await using ReviewsDbContext db = await dbFactory.CreateDbContextAsync();
        await db.Reviews.Where(r => r.Id == id)
            .ExecuteUpdateAsync(s => s.SetProperty(r => r.VerifiedAtUtc, clock.GetUtcNow().UtcDateTime));
    }
}
EOF
