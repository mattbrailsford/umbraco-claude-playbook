#!/usr/bin/env bash
set -euo pipefail
mkdir -p client/src/summary client/src/api
cat > client/package.json <<'EOF'
{
  "name": "page-summary-client",
  "private": true,
  "type": "module",
  "devDependencies": { "@umbraco-cms/backoffice": "^17.6.0", "typescript": "^5.9.0", "vite": "^7.0.0" }
}
EOF
cat > client/src/summary/summary.data-source.ts <<'EOF'
import type { UmbControllerHost } from '@umbraco-cms/backoffice/controller-api';
import { tryExecute } from '@umbraco-cms/backoffice/resources';
import { PageSummaryService } from '../api/index.js';

export interface PageSummary {
	/** The summary as HTML, written by the AI model from the page's rich text. */
	html: string;
	generatedAt: string;
}

export class PageSummaryDataSource {
	#host: UmbControllerHost;

	constructor(host: UmbControllerHost) {
		this.#host = host;
	}

	async get(documentKey: string) {
		const { data, error } = await tryExecute(this.#host, PageSummaryService.getSummary({ path: { documentKey } }));
		if (error || !data) return { error };
		return { data: { html: data.html, generatedAt: data.generatedAt } as PageSummary };
	}
}
EOF
cat > client/src/api/index.ts <<'EOF'
// Generated by @hey-api/openapi-ts from the package's Management API.
export class PageSummaryService {
	static getSummary(options: { path: { documentKey: string } }): Promise<{ data?: { html: string; generatedAt: string }; error?: unknown }> {
		throw new Error('generated');
	}
}
EOF
