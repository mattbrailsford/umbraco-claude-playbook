#!/usr/bin/env bash
set -euo pipefail
# This checkout is v16/main. A worktree of v17/main sits at .worktrees/v17-main.
write_tree() {
  local root=$1 cms=$2 ef=$3 with_verified=$4
  local d=$root/src/Acme.Reviews
  mkdir -p $d/Persistence $root/src/Acme.Reviews.Migrations.SqlServer/Migrations $root/src/Acme.Reviews.Migrations.Sqlite/Migrations
  cat > $d/Acme.Reviews.csproj <<EOF
<Project Sdk="Microsoft.NET.Sdk.Razor">
  <PropertyGroup><TargetFramework>net${ef}.0</TargetFramework><Nullable>enable</Nullable><ImplicitUsings>enable</ImplicitUsings></PropertyGroup>
  <ItemGroup>
    <PackageReference Include="Umbraco.Cms.Persistence.EFCore" Version="[${cms}.0.0, $((cms+1)))" />
  </ItemGroup>
</Project>
EOF
  local extra=""
  [ "$with_verified" = yes ] && extra=$'\n    public DateTime? VerifiedAtUtc { get; set; }'
  cat > $d/Persistence/Review.cs <<EOF
namespace Acme.Reviews.Persistence;

public class Review
{
    public int Id { get; set; }
    public Guid ContentKey { get; set; }
    public int Rating { get; set; }
    public DateTime CreatedUtc { get; set; }${extra}
}
EOF
  cat > $d/Persistence/ReviewsDbContext.cs <<'EOF'
using Microsoft.EntityFrameworkCore;

namespace Acme.Reviews.Persistence;

public class ReviewsDbContext(DbContextOptions<ReviewsDbContext> options) : DbContext(options)
{
    public DbSet<Review> Reviews => Set<Review>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
        => modelBuilder.Entity<Review>().ToTable("acmeReviews");
}
EOF
  for p in SqlServer Sqlite; do
    local m=$root/src/Acme.Reviews.Migrations.$p/Migrations
    local idtype=int; local dt=$([ $p = SqlServer ] && echo datetime2 || echo TEXT)
    cat > $m/20260310090000_AcmeReviews_Initial.cs <<EOF
