        {
            migrationBuilder.CreateTable(
                name: "acmeReviews",
                columns: table => new
                {
                    Id = table.Column<int>(nullable: false),
                    ContentKey = table.Column<Guid>(nullable: false),
                    Rating = table.Column<int>(nullable: false),
                    CreatedUtc = table.Column<DateTime>(type: "$dt", nullable: false)
                },
                constraints: table => table.PrimaryKey("PK_acmeReviews", x => x.Id));
        }

        /// <inheritdoc />
        protected override void Down(MigrationBuilder migrationBuilder)
            => migrationBuilder.DropTable(name: "acmeReviews");
    }
}
EOF
    cat > $m/20260310090000_AcmeReviews_Initial.Designer.cs <<EOF
