import { customElement, html, state } from '@umbraco-cms/backoffice/external/lit';
import { UmbLitElement } from '@umbraco-cms/backoffice/lit-element';
import type { StockAlertModel } from '../api/index.js';
import { StockAlertsDataSource } from './alerts-data-source.js';

@customElement('stock-alerts-dashboard')
export class StockAlertsDashboardElement extends UmbLitElement {
  #source = new StockAlertsDataSource(this);
  @state() private _alerts: StockAlertModel[] = [];

  override async connectedCallback() {
    super.connectedCallback();
    await this.#load();
  }

  async #load() {
    const { data } = await this.#source.getAll();
    this._alerts = data ?? [];
  }

  override render() {
    return html`<uui-box headline="Stock alerts">
      ${this._alerts.map(
        (a) => html`<div>${a.productName} below ${a.threshold}</div>`,
      )}
    </uui-box>`;
  }
}

export default StockAlertsDashboardElement;
